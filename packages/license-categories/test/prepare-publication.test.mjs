test('packed fixtures cover data-only releases, forced non-data dispatch, version gates, failures and reruns', async t => {
  const temporary = mkdtempSync(join(tmpdir(), 'license-categories-release-'))
  t.after(() => rmSync(temporary, {recursive: true, force: true}))
  const directory = join(temporary, 'package')
  mkdirSync(join(directory, 'dist'), {recursive: true})
  mkdirSync(join(directory, 'docs'))
  const writeVersion = version => {
    writeFileSync(join(directory, 'package.json'), JSON.stringify(manifest(version)))
    writeFileSync(join(directory, 'package-lock.json'), JSON.stringify(lock(version)))
  }
  writeVersion('1.0.0')
  writeFileSync(join(directory, 'dist/index.js'), 'export const answer = 42\n')
  const generated = (commit, value = data) => generatedSource(value).replace('a'.repeat(40), commit)
  writeFileSync(join(directory, 'dist/generated.js'), generated('a'.repeat(40)))
  writeFileSync(join(directory, 'README.md'), 'consumer guide')
  writeFileSync(join(directory, 'LICENSE'), 'MIT fixture')
  writeFileSync(join(directory, 'docs/operations.md'), 'excluded maintainer guide')
  const baseline = join(temporary, 'baseline.tgz')
  await create({cwd: temporary, file: baseline, gzip: true}, ['package/package.json', 'package/dist', 'package/README.md', 'package/LICENSE'])
  const bytes = readFileSync(baseline)
  const published = metadata('1.0.0')
  published.versions['1.0.0'].dist = {
    tarball: 'https://registry.npmjs.org/fixture.tgz',
    integrity: `sha512-${createHash('sha512').update(bytes).digest('base64')}`,
  }
  const fetcher = async url => String(url).endsWith('.tgz') ? new Response(bytes) : jsonResponse(published)
  const destination = join(temporary, 'candidate.tgz')
  const first = await preparePublication(directory, destination, async () => jsonResponse({error: 'Not found'}, 404))
  assert.equal(first.changed, true)
  const candidate = await packedFiles(destination)
  assert.ok(candidate.has('dist/index.js'))
  assert.ok(!candidate.has('docs/operations.md'))
  assert.equal((await preparePublication(directory, destination, fetcher)).changed, false)
  writeFileSync(join(directory, 'dist/generated.js'), generated('b'.repeat(40)))
  // A pin-only update skips before checking reuse of the published version.
  assert.equal((await preparePublication(directory, destination, fetcher)).changed, false)
  writeFileSync(join(directory, 'docs/operations.md'), 'changed excluded documentation')
  writeVersion('1.0.1')
  assert.equal((await preparePublication(directory, destination, fetcher)).changed, false)
  writeFileSync(join(directory, 'dist/index.js'), 'export const answer = 43\n')
  writeFileSync(join(directory, 'README.md'), 'changed consumer documentation')
  writeFileSync(join(directory, 'LICENSE'), 'changed license notice')
  assert.equal((await preparePublication(directory, destination, fetcher)).changed, false)
  const forced = await preparePublication(directory, destination, fetcher, {force: true})
  assert.equal(forced.changed, true)
  assert.match(forced.message, /Manual dispatch/)
  assert.equal((await packedFiles(destination)).get('dist/index.js').toString(), 'export const answer = 43\n')
  assert.equal((await packedFiles(destination)).get('README.md').toString(), 'changed consumer documentation')
  assert.deepEqual(generatedLicenseData(await packedFiles(destination)), data)
  writeFileSync(join(directory, 'package-lock.json'), JSON.stringify(lock('1.0.0')))
  await assert.rejects(preparePublication(directory, destination, fetcher, {force: true}), /must agree/)
  writeVersion('1.0.0')
  await assert.rejects(preparePublication(directory, destination, fetcher, {force: true}), /already published/)
  writeVersion('0.9.0')
  await assert.rejects(preparePublication(directory, destination, fetcher, {force: true}), /semantically newer/)
  writeVersion('1.0.0')
  assert.equal((await preparePublication(directory, destination, fetcher)).changed, false)
  const changedData = structuredClone(data)
  changedData.licensesById.MIT.name = 'Changed MIT name'
  writeFileSync(join(directory, 'dist/generated.js'), generated('b'.repeat(40), changedData))
  await assert.rejects(preparePublication(directory, destination, fetcher), /already published/)
  writeVersion('1.0.2')
  assert.equal((await preparePublication(directory, destination, fetcher)).changed, true)
  // A failed attempt can be retried while npm still serves the old baseline.
  assert.equal((await preparePublication(directory, destination, fetcher)).changed, true)
  const uploaded = readFileSync(destination)
  assert.equal((await packedFiles(destination)).get('dist/index.js').toString(), 'export const answer = 43\n')
  const nowPublished = metadata('1.0.2')
  nowPublished.versions['1.0.2'].dist = {
    tarball: 'https://registry.npmjs.org/uploaded.tgz',
    integrity: `sha512-${createHash('sha512').update(uploaded).digest('base64')}`,
  }
  assert.equal((await preparePublication(directory, destination, async url =>
    String(url).endsWith('.tgz') ? new Response(uploaded) : jsonResponse(nowPublished))).changed, false)
  await assert.rejects(preparePublication(directory, destination, async url =>
    String(url).endsWith('.tgz') ? new Response(uploaded) : jsonResponse(nowPublished), {force: true}), /already published/)
  await assert.rejects(preparePublication(directory, destination, async () => { throw new Error('offline') }), /offline/)
  published.time['1.0.2'] = '2026-02-01T00:00:00Z'
  rmSync(destination)
  await assert.rejects(preparePublication(directory, destination, fetcher), /already published/)
  assert.equal(existsSync(destination), false)
  await assert.rejects(preparePublication(directory, destination, async () => { throw new Error('offline') }, {force: true}), /offline/)
  // First publication still enforces the manifest/lockfile contract.
  writeFileSync(join(directory, 'package-lock.json'), JSON.stringify(lock('1.0.0')))
  await assert.rejects(preparePublication(directory, destination, async () => jsonResponse({error: 'Not found'}, 404)), /must agree/)
  writeVersion('1.0.2')
  writeFileSync(join(directory, 'dist/generated.js'), 'export const unsupported = "data";')
  const malformedPath = join(temporary, 'malformed.tgz')
  await create({cwd: temporary, file: malformedPath, gzip: true}, ['package/package.json', 'package/dist'])
  const malformed = readFileSync(malformedPath)
  const malformedMetadata = metadata('1.0.0')
  malformedMetadata.versions['1.0.0'].dist = {
    tarball: 'https://registry.npmjs.org/malformed.tgz',
    integrity: `sha512-${createHash('sha512').update(malformed).digest('base64')}`,
  }
  await assert.rejects(preparePublication(directory, destination, fetcher, {force: true}), /Unsupported generated license data/)
  writeFileSync(join(directory, 'dist/generated.js'), generated('b'.repeat(40), changedData))
  const malformedFetcher = async url => String(url).endsWith('.tgz') ? new Response(malformed) : jsonResponse(malformedMetadata)
  await assert.rejects(preparePublication(directory, destination, malformedFetcher), /Unsupported generated license data/)
  await assert.rejects(preparePublication(directory, destination, malformedFetcher, {force: true}), /Unsupported generated license data/)
  rmSync(join(directory, 'dist/generated.js'))
  await assert.rejects(preparePublication(directory, destination, async () => jsonResponse({error: 'Not found'}, 404)), /missing dist\/generated.js/)
})
