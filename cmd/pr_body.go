package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

func generatePRBody(outputPath string) error {
	repositoryRootOutput, err := exec.Command("git", "rev-parse", "--show-toplevel").Output()
	if err != nil {
		return fmt.Errorf("find repository root: %w", err)
	}
	repositoryRoot := strings.TrimSpace(string(repositoryRootOutput))

	var previousLicenses, currentLicenses LicenseData
	if err := decodePreviousJSON(repositoryRoot, "cmd/licenses.json", &previousLicenses); err != nil {
		return err
	}
	if err := decodeJSONFile(filepath.Join(repositoryRoot, "cmd/licenses.json"), &currentLicenses); err != nil {
		return err
	}

	var previousExceptions, currentExceptions ExceptionData
	if err := decodePreviousJSON(repositoryRoot, "cmd/exceptions.json", &previousExceptions); err != nil {
		return err
	}
	if err := decodeJSONFile(filepath.Join(repositoryRoot, "cmd/exceptions.json"), &currentExceptions); err != nil {
		return err
	}

	body := buildPRBody(previousLicenses, currentLicenses, previousExceptions, currentExceptions)
	if err := os.WriteFile(outputPath, []byte(body), 0600); err != nil {
		return fmt.Errorf("write PR body: %w", err)
	}
	return nil
}

func decodePreviousJSON(repositoryRoot, path string, destination any) error {
	contents, err := exec.Command("git", "-C", repositoryRoot, "show", "HEAD:"+path).Output()
	if err != nil {
		return fmt.Errorf("read previous %s: %w", path, err)
	}
	if err := json.Unmarshal(contents, destination); err != nil {
		return fmt.Errorf("decode previous %s: %w", path, err)
	}
	return nil
}

func decodeJSONFile(path string, destination any) error {
	contents, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("read %s: %w", path, err)
	}
	if err := json.Unmarshal(contents, destination); err != nil {
		return fmt.Errorf("decode %s: %w", path, err)
	}
	return nil
}

func buildPRBody(previousLicenses, currentLicenses LicenseData, previousExceptions, currentExceptions ExceptionData) string {
	var body bytes.Buffer
	body.WriteString("> [!WARNING]\n")
	body.WriteString("> Do not push commits directly to this PR's `auto-update-licenses` branch or manually edit this description. The nightly workflow updates both and may overwrite manual changes. For changes that depend on this update, open a stacked PR with `auto-update-licenses` as its base. For generator or workflow fixes that must persist, open a separate PR against `main`, merge it, and rerun this workflow.\n\n")
	body.WriteString("This PR was generated by the [fetch-licenses](./.github/workflows/fetch-licenses.yaml) workflow from [spdx/license-list-data](https://github.com/spdx/license-list-data).\n\n")
	fmt.Fprintf(&body, "- **Previous SPDX License List Version:** `%s`\n", previousLicenses.Version)
	fmt.Fprintf(&body, "- **New SPDX License List Version:** `%s`\n\n", currentLicenses.Version)

	body.WriteString("## SPDX changes\n\n")

	previousLicenseStatuses := licenseStatuses(previousLicenses.Licenses)
	currentLicenseStatuses := licenseStatuses(currentLicenses.Licenses)
	writeChanges(&body, "Licenses", addedIDs(previousLicenseStatuses, currentLicenseStatuses), removedIDs(previousLicenseStatuses, currentLicenseStatuses))

	previousExceptionStatuses := exceptionStatuses(previousExceptions.Exceptions)
	currentExceptionStatuses := exceptionStatuses(currentExceptions.Exceptions)
	writeChanges(&body, "Exceptions", addedIDs(previousExceptionStatuses, currentExceptionStatuses), removedIDs(previousExceptionStatuses, currentExceptionStatuses))

	body.WriteString("### Deprecations\n\n")
	writeIDList(&body, "Newly deprecated licenses", changedStatusIDs(previousLicenseStatuses, currentLicenseStatuses, true))
	writeIDList(&body, "Reactivated licenses", changedStatusIDs(previousLicenseStatuses, currentLicenseStatuses, false))
	writeIDList(&body, "Newly deprecated exceptions", changedStatusIDs(previousExceptionStatuses, currentExceptionStatuses, true))
	writeIDList(&body, "Reactivated exceptions", changedStatusIDs(previousExceptionStatuses, currentExceptionStatuses, false))

	body.WriteString("\n### License range families\n\n")
	writeIDList(&body, "Added", changedLicenseRangeFamilies(previousLicenses.Licenses, currentLicenses.Licenses))
	writeIDList(&body, "Removed", removedLicenseRangeFamilies(previousLicenses.Licenses, currentLicenses.Licenses))

	body.WriteString("\n## Review instructions (human and Copilot)\n\n")
	body.WriteString("Use the summary above as the expected change set and report any discrepancy between it, the source JSON, and the generated files. Focus review on these invariants:\n\n")
	body.WriteString("- Active and deprecated license IDs appear in the matching generated collection. Non-deprecated exception IDs appear in the generated exception collection; deprecated exceptions are intentionally excluded.\n")
	body.WriteString("- Any added license range family contains at least two versions, keeps equivalent `-only` IDs in the same version group, and is sorted in semantic version order.\n")
	body.WriteString("- Copilot: If **Added** or **Removed** under **License range families** is not `None`, leave an inline review comment on the relevant generated family block beginning with **Human review required: license range family changed**.\n")
	body.WriteString("- Generated files contain no unrelated changes. Changes should be made in the generator or source data, not directly in generated files.\n")
	body.WriteString("- Pay particular attention to IDs that moved between active and deprecated collections; these are status changes, not additions or removals.\n")
	return body.String()
}

func licenseStatuses(licenses []License) map[string]bool {
	statuses := make(map[string]bool, len(licenses))
	for _, license := range licenses {
		statuses[license.LicenseID] = license.IsDeprecated
	}
	return statuses
}

func exceptionStatuses(exceptions []Exception) map[string]bool {
	statuses := make(map[string]bool, len(exceptions))
	for _, exception := range exceptions {
		statuses[exception.LicenseID] = exception.IsDeprecated
	}
	return statuses
}

func addedIDs(previous, current map[string]bool) []string {
	return mapDifference(current, previous)
}

func removedIDs(previous, current map[string]bool) []string {
	return mapDifference(previous, current)
}

func mapDifference(first, second map[string]bool) []string {
	ids := make([]string, 0)
	for id := range first {
		if _, exists := second[id]; !exists {
			ids = append(ids, id)
		}
	}
	sort.Strings(ids)
	return ids
}

func changedStatusIDs(previous, current map[string]bool, deprecated bool) []string {
	ids := make([]string, 0)
	for id, currentStatus := range current {
		previousStatus, exists := previous[id]
		if exists && previousStatus != currentStatus && currentStatus == deprecated {
			ids = append(ids, id)
		}
	}
	sort.Strings(ids)
	return ids
}

func changedLicenseRangeFamilies(previous, current []License) []string {
	previousFamilies := buildLicenseRangeFamilies(previous, includedLicenseRangeFamilies, excludedLicenseRangeFamilyBases)
	currentFamilies := buildLicenseRangeFamilies(current, includedLicenseRangeFamilies, excludedLicenseRangeFamilyBases)
	previousKeys := make(map[string]struct{}, len(previousFamilies))
	for _, family := range previousFamilies {
		previousKeys[family.base+"\x00"+family.suffix] = struct{}{}
	}

	added := make([]string, 0)
	for _, family := range currentFamilies {
		if _, exists := previousKeys[family.base+"\x00"+family.suffix]; !exists {
			added = append(added, family.base+"-<version>"+family.suffix)
		}
	}
	return added
}

func removedLicenseRangeFamilies(previous, current []License) []string {
	previousFamilies := buildLicenseRangeFamilies(previous, includedLicenseRangeFamilies, excludedLicenseRangeFamilyBases)
	currentFamilies := buildLicenseRangeFamilies(current, includedLicenseRangeFamilies, excludedLicenseRangeFamilyBases)
	currentKeys := make(map[string]struct{}, len(currentFamilies))
	for _, family := range currentFamilies {
		currentKeys[family.base+"\x00"+family.suffix] = struct{}{}
	}

	removed := make([]string, 0)
	for _, family := range previousFamilies {
		if _, exists := currentKeys[family.base+"\x00"+family.suffix]; !exists {
			removed = append(removed, family.base+"-<version>"+family.suffix)
		}
	}
	return removed
}

func writeChanges(body *bytes.Buffer, heading string, added, removed []string) {
	fmt.Fprintf(body, "### %s\n\n", heading)
	writeIDList(body, "Added", added)
	writeIDList(body, "Removed", removed)
	body.WriteString("\n")
}

func writeIDList(body *bytes.Buffer, label string, ids []string) {
	fmt.Fprintf(body, "- **%s:** ", label)
	if len(ids) == 0 {
		body.WriteString("None\n")
		return
	}
	formatted := make([]string, len(ids))
	for index, id := range ids {
		formatted[index] = "`" + id + "`"
	}
	body.WriteString(strings.Join(formatted, ", "))
	body.WriteByte('\n')
}
