package main

import (
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type licenseRangeFamily struct {
	base                string
	suffix              string
	inheritBaseVersions bool
}

var includedLicenseRangeFamilies = []licenseRangeFamily{
	{base: "Brian-Gladman", suffix: "-Clause"},
	{base: "MPL", suffix: "-no-copyleft-exception", inheritBaseVersions: true},
}

var excludedLicenseRangeFamilyBases = map[string]struct{}{
	"Spencer": {},
}

const licenseVersionPattern = `\d+(?:\.\d+)*(?:[a-z])?`

var standardLicenseVersionPattern = regexp.MustCompile("^(.+)-(" + licenseVersionPattern + ")$")

func generateLicenseRanges(licenses []License, outputPath string) error {
	ranges := buildLicenseRanges(licenses)
	contents := []byte(`package spdxlicenses

// Code generated by go-spdx cmd/license_ranges.go. DO NOT EDIT.
// Source: https://github.com/spdx/license-list-data specifies official SPDX license list.

// LicenseRanges returns license version groups in ascending version order.
// IDs within the same version group are equivalent (for example, GPL-2.0 and GPL-2.0-only).
func LicenseRanges() [][][]string {
	return [][][]string{
`)
	for _, family := range ranges {
		contents = append(contents, "\t\t{\n"...)
		for _, version := range family {
			contents = append(contents, "\t\t\t{\n"...)
			for _, id := range version {
				contents = append(contents, fmt.Sprintf("\t\t\t\t%q,\n", id)...)
			}
			contents = append(contents, "\t\t\t},\n"...)
		}
		contents = append(contents, "\t\t},\n"...)
	}
	contents = append(contents, "\t}\n}\n"...)

	contents, err := format.Source(contents)
	if err != nil {
		return fmt.Errorf("format generated license_ranges.go: %w", err)
	}
	if err := os.WriteFile(outputPath, contents, 0600); err != nil {
		return err
	}
	fmt.Println("Writing `../spdxexp/spdxlicenses/license_ranges.go`... COMPLETE")
	return nil
}

func buildLicenseRanges(licenses []License) [][][]string {
	licenseIDs := make(map[string]struct{}, len(licenses))
	for _, license := range licenses {
		licenseIDs[license.LicenseID] = struct{}{}
	}

	families := buildLicenseRangeFamilies(licenses, includedLicenseRangeFamilies, excludedLicenseRangeFamilyBases)
	ranges := make([][][]string, 0, len(families))
	for _, family := range families {
		pattern := regexp.MustCompile("^" + regexp.QuoteMeta(family.base) + "-(" + licenseVersionPattern + ")" + regexp.QuoteMeta(family.suffix) + "$")
		versions := make(map[string][]string)
		for id := range licenseIDs {
			matches := pattern.FindStringSubmatch(id)
			if matches == nil {
				continue
			}
			versions[matches[1]] = append(versions[matches[1]], id)
			if family.suffix == "" {
				onlyID := id + "-only"
				if _, ok := licenseIDs[onlyID]; ok {
					versions[matches[1]] = append(versions[matches[1]], onlyID)
				}
			}
		}
		if family.inheritBaseVersions {
			basePattern := regexp.MustCompile("^" + regexp.QuoteMeta(family.base) + "-(" + licenseVersionPattern + ")$")
			for id := range licenseIDs {
				matches := basePattern.FindStringSubmatch(id)
				if matches != nil {
					if _, overridden := versions[matches[1]]; !overridden {
						versions[matches[1]] = []string{id}
					}
				}
			}
		}

		versionNames := make([]string, 0, len(versions))
		for version := range versions {
			versionNames = append(versionNames, version)
		}
		sort.Slice(versionNames, func(i, j int) bool {
			return compareLicenseVersions(versionNames[i], versionNames[j]) < 0
		})

		licenseGroup := make([][]string, 0, len(versionNames))
		for _, version := range versionNames {
			sort.Strings(versions[version])
			licenseGroup = append(licenseGroup, versions[version])
		}
		if len(licenseGroup) > 1 {
			ranges = append(ranges, licenseGroup)
		}
	}
	return ranges
}

func buildLicenseRangeFamilies(licenses []License, included []licenseRangeFamily, excluded map[string]struct{}) []licenseRangeFamily {
	versionsByBase := make(map[string]map[string]struct{})
	for _, license := range licenses {
		matches := standardLicenseVersionPattern.FindStringSubmatch(license.LicenseID)
		if matches == nil {
			continue
		}
		if _, excluded := excluded[matches[1]]; excluded {
			continue
		}
		if versionsByBase[matches[1]] == nil {
			versionsByBase[matches[1]] = make(map[string]struct{})
		}
		versionsByBase[matches[1]][matches[2]] = struct{}{}
	}

	familiesByKey := make(map[string]licenseRangeFamily, len(versionsByBase)+len(included))
	for base, versions := range versionsByBase {
		if len(versions) > 1 {
			familiesByKey[base+"\x00"] = licenseRangeFamily{base: base}
		}
	}
	for _, family := range included {
		familiesByKey[family.base+"\x00"+family.suffix] = family
	}

	families := make([]licenseRangeFamily, 0, len(familiesByKey))
	for _, family := range familiesByKey {
		families = append(families, family)
	}
	sort.Slice(families, func(i, j int) bool {
		firstBase := strings.ToLower(families[i].base)
		secondBase := strings.ToLower(families[j].base)
		if firstBase != secondBase {
			return firstBase < secondBase
		}
		if families[i].base != families[j].base {
			return families[i].base < families[j].base
		}
		return families[i].suffix < families[j].suffix
	})
	return families
}

func compareLicenseVersions(first, second string) int {
	firstParts := strings.FieldsFunc(first, func(r rune) bool { return r == '.' })
	secondParts := strings.FieldsFunc(second, func(r rune) bool { return r == '.' })
	for i := 0; i < len(firstParts) && i < len(secondParts); i++ {
		firstNumber, firstSuffix := splitVersionPart(firstParts[i])
		secondNumber, secondSuffix := splitVersionPart(secondParts[i])
		if firstNumber != secondNumber {
			return firstNumber - secondNumber
		}
		if firstSuffix != secondSuffix {
			return strings.Compare(firstSuffix, secondSuffix)
		}
	}
	return len(firstParts) - len(secondParts)
}

func splitVersionPart(part string) (int, string) {
	index := 0
	for index < len(part) && part[index] >= '0' && part[index] <= '9' {
		index++
	}
	number, _ := strconv.Atoi(part[:index])
	return number, part[index:]
}
